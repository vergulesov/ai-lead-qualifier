import os
import requests
from dotenv import load_dotenv


load_dotenv()

BITRIX_WEBHOOK_URL = os.getenv("BITRIX_WEBHOOK_URL")

if not BITRIX_WEBHOOK_URL:
    raise RuntimeError("Не найден BITRIX_WEBHOOK_URL в .env")


def bitrix_call(method, data):
    url = f"{BITRIX_WEBHOOK_URL.rstrip('/')}/{method}.json"

    response = requests.post(
        url,
        json=data,
        timeout=30,
    )

    response.raise_for_status()

    result = response.json()

    if "error" in result:
        raise RuntimeError(
            f"Bitrix API error: {result.get('error')}: "
            f"{result.get('error_description')}"
        )

    return result


def create_deal(title, amount):
    result = bitrix_call(
        "crm.deal.add",
        {
            "fields": {
                "TITLE": title,
                "OPPORTUNITY": amount,
                "CURRENCY_ID": "RUB",
            }
        },
    )

    return result["result"]


def add_timeline_comment(deal_id, text):
    result = bitrix_call(
        "crm.timeline.comment.add",
        {
            "fields": {
                "ENTITY_ID": deal_id,
                "ENTITY_TYPE": "deal",
                "COMMENT": text,
            }
        },
    )

    return result["result"]


