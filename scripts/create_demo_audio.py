import asyncio
import subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg


TEXT = """
Василий: Добрый день! Меня зовут Василий, компания Best Paints. Вы оставляли заявку по поводу покраски дома, удобно сейчас пару минут поговорить?

Клиент: Да, здравствуйте.

Василий: Расскажите, что хотели бы сделать?

Клиент: Ну, дом у нас деревянный, лет десять ему уже. Снаружи красили когда-то, сейчас выглядит так себе. Хотим привести в порядок.

Василий: Понял. А что именно с покрытием?

Клиент: Где-то нормально ещё, а где-то совсем выгорело и потрескалось. На солнечной стороне особенно. В некоторых местах вообще отслаивается.

Василий: Понятно. А по размерам примерно что за дом?

Клиент: Точно не скажу. Сам дом где-то метров 180, может 190. А фасада, насколько я помню, около 250–280 квадратов.

Василий: Хорошо. А где находится?

Клиент: В Челябинске, за городом немного. Садовое товарищество, название сейчас не вспомню.

Василий: Фото можете прислать?

Клиент: Да, фотографии сделаю. Сегодня вечером, скорее всего. Проекта у меня нет.

Василий: Хорошо. Нам подойдёт либо проект, либо фотографии, чтобы предварительно оценить объём.

Клиент: Фотографии тогда скину.

Василий: По результату что хотите получить? Просто освежить покрытие или полностью переделать?

Клиент: Я думаю, полностью. Сначала подготовить поверхность, где-то старую краску снять, потом нормально покрасить. Цвет жена хочет поменять, сейчас какой-то тёмный коричневый, хотим посветлее.

Василий: Понял. По срокам когда хотелось бы заняться?

Клиент: Если всё нормально по деньгам, то в течение месяца. Может чуть раньше.

Василий: А по бюджету хотя бы ориентир есть?

Клиент: Ну вот тут сложно. Я смотрел в интернете, там вообще от 200 тысяч до миллиона цены. Мы рассчитывали, наверное, тысяч на 500–600. Ну максимум, наверное, 700.

Василий: Понял. То есть ориентир до 700 тысяч?

Клиент: Да, но если там реально сильно отличается по объёму, будем смотреть. Просто миллион мы точно не планировали.

Василий: Ещё какие-то работы кроме фасада нужны? Терраса, окна, какие-то дополнительные конструкции?

Клиент: Возможно, террасу тоже надо будет покрасить. Там небольшая пристройка. Но я пока не знаю, жена хочет сначала с фасадом разобраться.

Василий: Хорошо, тогда пока зафиксируем основной объём. Сегодня ждём фотографии, после этого сможем сделать предварительную оценку.

Клиент: Договорились.

Василий: Отлично. Тогда как фотографии будут — присылайте, и мы посмотрим, что можно предложить.

Клиент: Хорошо, спасибо.
"""


async def main():
    mp3_path = Path("demo_voice.mp3")
    ogg_path = Path("demo_voice.ogg")

    print("Генерируем речь...")

    communicate = edge_tts.Communicate(
        TEXT,
        voice="ru-RU-DmitryNeural",
        rate="-5%",
        volume="+0%",
    )

    await communicate.save(str(mp3_path))

    print("Конвертируем MP3 → OGG...")

    ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()

    subprocess.run(
        [
            ffmpeg,
            "-y",
            "-i",
            str(mp3_path),
            "-c:a",
            "libopus",
            "-b:a",
            "64k",
            str(ogg_path),
        ],
        check=True,
    )

    print()
    print("ГОТОВО")
    print(f"Файл: {ogg_path.resolve()}")
    print(f"Размер: {ogg_path.stat().st_size / 1024:.1f} KB")


if __name__ == "__main__":
    asyncio.run(main())